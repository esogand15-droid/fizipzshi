def block_end_index(src: str, anchor: str) -> int | None:
    parts = re.split(r"\n(?=    \{)", src)
    hits = [i for i, p in enumerate(parts) if anchor in p]
    if len(hits) != 1:
        print(f"!! anchor matched {len(hits)}x: {anchor[:50]!r}")
        return None
    return hits[0]


def fmt_blocks(blocks: list[dict]) -> str:
    out = []
    for b in blocks:
        lines = ["    {"]
        for k, v in b.items():
            val = "h3" if v == "h3less" else v
            lines.append(f"     {k!r}: {val!r},")
        lines[-1] = lines[-1].rstrip(",")
        lines.append("     },\n")
        out.append("\n".join(lines))
    return "".join(out)


def main() -> int:
    total = 0
    for fname, entries in PLAN.items():
        path = CONTENT / fname
        src = path.read_text(encoding="utf-8")
        added = 0
        for anchor, blocks in entries:
            sigs = []
            for b in blocks:
                if b.get("text"):
                    sigs.append(b["text"][:48])
                elif b.get("items"):
                    sigs.append(b["items"][0][:48])
                elif b.get("head"):
                    sigs.append(b["head"][0])
            if any(sg and sg in src for sg in sigs):
                continue  # group already inserted (idempotent)
            idx = block_end_index(src, anchor)
            if idx is None:
                continue
            parts = re.split(r"\n(?=    \{)", src)
            blob = fmt_blocks(blocks)
            parts[idx] = parts[idx].rstrip("\n") + "\n" + blob
            src = "\n".join(parts)
            added += len(blocks)
        if added:
            path.write_text(src, encoding="utf-8")
            print(f"{fname}: +{added} video blocks")
            total += added
        else:
            print(f"{fname}: nothing added")
    print("total", total)
    return 0


